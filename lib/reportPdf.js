// Builds the report PDF with jsPDF + jspdf-autotable (pure JavaScript, so it runs on Vercel serverless).
// Noto Sans is embedded (lib/fonts/notoSans.js) so the Rupee sign (₹) prints correctly.
import { jsPDF } from "jspdf";
import { autoTable } from "jspdf-autotable";
import { NOTO_REGULAR, NOTO_BOLD } from "./fonts/notoSans";
import { floorName, typeName } from "./floors";

const INK = [19, 15, 38];      // kit black #130F26
const YELLOW = [254, 217, 77]; // kit yellow #FED94D
const GREY = [108, 114, 127];
const FONT = "NotoSans";

const rs = (n) => "₹ " + Number(n || 0).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const cut = (s, n) => (s ? String(s).slice(0, n) : "-");

export function reportPdf(r) {
  const m = r.meta, s = r.summary;
  const doc = new jsPDF({ orientation: "landscape", unit: "mm", format: "a4" });
  doc.addFileToVFS("NotoSans-Regular.ttf", NOTO_REGULAR);
  doc.addFont("NotoSans-Regular.ttf", FONT, "normal");
  doc.addFileToVFS("NotoSans-Bold.ttf", NOTO_BOLD);
  doc.addFont("NotoSans-Bold.ttf", FONT, "bold");
  doc.setFont(FONT, "normal");
  doc.setProperties({ title: `Smart Parking Report ${m.from} to ${m.to}`, author: "Smart Parking Management System" });

  const W = doc.internal.pageSize.getWidth(), H = doc.internal.pageSize.getHeight();
  const TOTAL = "{total_pages}";
  let y = 26;

  // Black band with a yellow "P" mark, like the app's sidebar
  function header() {
    doc.setFillColor(...INK); doc.rect(0, 0, W, 18, "F");
    doc.setFillColor(...YELLOW); doc.roundedRect(10, 4, 10, 10, 2.5, 2.5, "F");
    doc.setTextColor(...INK); doc.setFont(FONT, "bold"); doc.setFontSize(11); doc.text("P", 15, 11, { align: "center" });
    doc.setTextColor(255); doc.setFontSize(13); doc.text("Smart Parking - Admin Report", 24, 11);
    doc.setFont(FONT, "normal"); doc.setFontSize(9);
    doc.text(`${m.from} to ${m.to}  |  generated ${m.generated_at} IST`, W - 10, 11, { align: "right" });
  }
  function footer(page) {
    doc.setFont(FONT, "normal"); doc.setFontSize(8); doc.setTextColor(...GREY);
    doc.text(`Smart Parking Management System  |  Page ${page} of ${TOTAL}`, W / 2, H - 6, { align: "center" });
  }
  const pageDeco = (data) => { header(); footer(data.pageNumber); };

  function section(title) {
    if (y > H - 40) { doc.addPage(); header(); footer(doc.getNumberOfPages()); y = 26; }
    doc.setFont(FONT, "bold"); doc.setFontSize(12); doc.setTextColor(...INK);
    doc.text(title, 10, y + 4);
    doc.setDrawColor(...YELLOW); doc.setLineWidth(1); doc.line(10, y + 6.5, 40, y + 6.5);
    y += 10;
  }
  // Table with a header row repeated on every page. align: array of 'left' | 'right'
  function table(head, rows, { widths, align = [], fontSize = 8.5 } = {}) {
    const columnStyles = {};
    head.forEach((_, i) => { columnStyles[i] = { halign: align[i] || "left", ...(widths ? { cellWidth: widths[i] } : {}) }; });
    autoTable(doc, {
      startY: y, head: [head], body: rows.length ? rows : [[{ content: "No data for this range.", colSpan: head.length, styles: { halign: "center" } }]],
      margin: { top: 24, left: 10, right: 10, bottom: 14 },
      styles: { font: FONT, fontSize, cellPadding: 1.4, textColor: INK, lineColor: [229, 230, 235], lineWidth: 0.2, overflow: "ellipsize" },
      headStyles: { font: FONT, fontStyle: "bold", fillColor: [244, 244, 246], textColor: INK },
      alternateRowStyles: { fillColor: [249, 250, 251] },
      columnStyles, didDrawPage: pageDeco,
    });
    y = doc.lastAutoTable.finalY + 6;
  }
  function kv(pairs) {
    autoTable(doc, {
      startY: y, body: pairs, theme: "plain", margin: { top: 24, left: 10, right: 10, bottom: 14 },
      styles: { font: FONT, fontSize: 9.5, cellPadding: 1.2, textColor: INK },
      columnStyles: { 0: { cellWidth: 80, textColor: GREY }, 1: { fontStyle: "bold" } }, didDrawPage: pageDeco,
    });
    y = doc.lastAutoTable.finalY + 6;
  }

  header(); footer(1);
  section("Summary");
  const st = s.status;
  kv([
    ["Date range", `${m.from} to ${m.to} (by booking start time, IST)`],
    ["Generated by", m.generated_by || "-"],
    ["Total bookings", `${s.total_bookings}   (booked ${st.booked}, entered ${st.entered}, completed ${st.completed}, cancelled ${st.cancelled})`],
    ["Revenue (paid, not cancelled)", rs(s.revenue_paid)],
    ["Pending payment", rs(s.pending_amount)],
    ["Average paid booking", rs(s.avg_paid_booking)],
    ["Hours booked (excl. cancelled)", String(s.booked_hours)],
    ["Customers with bookings / registered users", `${s.unique_customers} / ${s.registered_users}`],
    ["Active slots / average occupancy", `${r.inventory.total.active_slots} / ${r.inventory.total.occupancy_pct}%`],
  ]);

  const R8 = ["left", "left", "right", "right", "right", "right", "right", "right"];
  section("Occupancy by floor (all locations)");
  table(["Floor", "Name", "Active slots", "Inactive", "Bookings", "Booked hours", "Occupancy", "Occupied now"],
    Object.entries(r.inventory.by_floor).map(([k, a]) => [k, floorName(k), a.active_slots, a.inactive_slots, a.bookings, a.booked_hours, a.occupancy_pct + "%", a.occupied_now]),
    { align: R8, fontSize: 9 });
  section("Occupancy by vehicle type (all locations)");
  table(["Type", "Name", "Active slots", "Inactive", "Bookings", "Booked hours", "Occupancy", "Occupied now"],
    Object.entries(r.inventory.by_type).map(([k, a]) => [k, typeName(k), a.active_slots, a.inactive_slots, a.bookings, a.booked_hours, a.occupancy_pct + "%", a.occupied_now]),
    { align: R8, fontSize: 9 });

  section("Revenue breakdown");
  table(["Group", "Value", "Bookings", "Hours", "Revenue"], [
    ...Object.entries(r.revenue.by_location).map(([k, a]) => ["Location", k, a.bookings, a.hours, rs(a.revenue)]),
    ...Object.entries(r.revenue.by_floor).map(([k, a]) => ["Floor", `${k} - ${floorName(k)}`, a.bookings, a.hours, rs(a.revenue)]),
    ...Object.entries(r.revenue.by_type).map(([k, a]) => ["Vehicle type", `${k} - ${typeName(k)}`, a.bookings, a.hours, rs(a.revenue)]),
  ], { align: ["left", "left", "right", "right", "right"], fontSize: 9 });
  section("Revenue by day");
  table(["Date", "Bookings", "Hours", "Revenue"], Object.entries(r.revenue.by_day).map(([k, a]) => [k, a.bookings, a.hours, rs(a.revenue)]),
    { align: ["left", "right", "right", "right"], fontSize: 9 });

  doc.addPage(); header(); footer(doc.getNumberOfPages()); y = 26;
  section("Slot inventory and occupancy by location, floor and type");
  table(["Location", "Floor", "Type", "Active", "Inactive", "Bookings", "Booked h", "Occupancy", "Now"],
    r.inventory.rows.map((x) => [x.location_name, `${x.floor} - ${x.floor_name}`, `${x.vehicle_type} - ${x.type_name}`,
      x.active_slots, x.inactive_slots, x.bookings, x.booked_hours, x.occupancy_pct + "%", x.occupied_now]),
    { align: ["left", "left", "left", "right", "right", "right", "right", "right", "right"] });

  doc.addPage(); header(); footer(doc.getNumberOfPages()); y = 26;
  section(`Bookings (${r.bookings.length})`);
  table(["#", "User", "Location", "Slot", "Floor", "Type", "Vehicle", "Start", "End", "Hrs", "Amount", "Status", "Payment"],
    r.bookings.map((b) => [b.id, b.user_name, b.location_name, b.slot_label, b.floor, b.type_name, b.vehicle_number,
      cut(b.start_time, 16), cut(b.end_time, 16), b.hours, rs(b.amount), b.status, b.payment_status]),
    { align: ["right", "left", "left", "left", "left", "left", "left", "left", "left", "right", "right", "left", "left"], fontSize: 7.5 });
  section("Booking payment and gate details");
  table(["#", "Email", "Phone", "Created", "Payment ref", "Paid at", "Entry", "Exit"],
    r.bookings.map((b) => [b.id, b.user_email, b.user_phone || "-", cut(b.created_at, 16), b.payment_ref || "-",
      cut(b.paid_at, 16), cut(b.entry_time, 16), cut(b.exit_time, 16)]), { fontSize: 8 });
  section(`Users (${r.users.length})`);
  table(["ID", "Name", "Email", "Phone", "Role", "Registered", "Bookings (all)", "In range", "Paid in range"],
    r.users.map((u) => [u.id, u.name, u.email, u.phone || "-", u.role, cut(u.created_at, 10), u.bookings_all_time, u.bookings_in_range, rs(u.paid_in_range)]),
    { align: ["right", "left", "left", "left", "left", "left", "right", "right", "right"], fontSize: 8 });

  doc.putTotalPages(TOTAL);
  return Buffer.from(doc.output("arraybuffer"));
}
