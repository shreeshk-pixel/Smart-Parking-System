// Writes the report as one CSV file with titled sections (opens directly in Excel).
import { floorName, typeName } from "./floors";

// Text that starts with = + - @ (or tab / carriage return) would run as a formula in Excel or Sheets
// ("CSV injection"), so it gets a leading apostrophe. Real numbers are left alone.
const cell = (v) => {
  let s = v === null || v === undefined ? "" : String(v);
  if (typeof v === "string" && /^[=+\-@\t\r]/.test(s) && !/^-?\d+(\.\d+)?$/.test(s)) s = "'" + s;
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export function reportCsv(r) {
  const lines = [];
  const row = (cells) => lines.push(cells.map(cell).join(","));
  const section = (title) => { lines.push(""); row([`## ${title}`]); };
  const m = r.meta, s = r.summary;

  row(["Smart Parking Management System - Admin Report"]);
  row(["From", m.from]); row(["To", m.to]);
  row(["Generated at", m.generated_at + " IST"]); row(["Generated by", m.generated_by]);

  section("Summary");
  row(["Metric", "Value"]);
  row(["Total bookings", s.total_bookings]);
  for (const [k, v] of Object.entries(s.status)) row([`Bookings ${k}`, v]);
  row(["Revenue (paid, not cancelled) ₹", s.revenue_paid]);
  row(["Pending payment ₹", s.pending_amount]);
  row(["Average paid booking ₹", s.avg_paid_booking]);
  row(["Hours booked (excl. cancelled)", s.booked_hours]);
  row(["Customers with bookings", s.unique_customers]);
  row(["Registered users", s.registered_users]);
  row(["Average occupancy %", r.inventory.total.occupancy_pct]);

  section("Revenue by location");
  row(["Location", "Bookings", "Hours", "Revenue ₹"]);
  for (const [k, a] of Object.entries(r.revenue.by_location)) row([k, a.bookings, a.hours, a.revenue]);
  section("Revenue by floor");
  row(["Floor", "Floor name", "Bookings", "Hours", "Revenue ₹"]);
  for (const [k, a] of Object.entries(r.revenue.by_floor)) row([k, floorName(k), a.bookings, a.hours, a.revenue]);
  section("Revenue by vehicle type");
  row(["Type", "Type name", "Bookings", "Hours", "Revenue ₹"]);
  for (const [k, a] of Object.entries(r.revenue.by_type)) row([k, typeName(k), a.bookings, a.hours, a.revenue]);
  section("Revenue by day");
  row(["Date", "Bookings", "Hours", "Revenue ₹"]);
  for (const [k, a] of Object.entries(r.revenue.by_day)) row([k, a.bookings, a.hours, a.revenue]);

  section("Slot inventory and occupancy by location, floor and type");
  row(["Location", "Floor", "Floor name", "Type", "Type name", "Active slots", "Inactive slots", "Bookings", "Booked hours", "Occupancy %", "Occupied now"]);
  for (const x of r.inventory.rows) row([x.location_name, x.floor, x.floor_name, x.vehicle_type, x.type_name,
    x.active_slots, x.inactive_slots, x.bookings, x.booked_hours, x.occupancy_pct, x.occupied_now]);
  section("Occupancy by floor (all locations)");
  row(["Floor", "Floor name", "Active slots", "Inactive slots", "Bookings", "Booked hours", "Occupancy %", "Occupied now"]);
  for (const [k, a] of Object.entries(r.inventory.by_floor)) row([k, floorName(k), a.active_slots, a.inactive_slots, a.bookings, a.booked_hours, a.occupancy_pct, a.occupied_now]);
  section("Occupancy by vehicle type (all locations)");
  row(["Type", "Type name", "Active slots", "Inactive slots", "Bookings", "Booked hours", "Occupancy %", "Occupied now"]);
  for (const [k, a] of Object.entries(r.inventory.by_type)) row([k, typeName(k), a.active_slots, a.inactive_slots, a.bookings, a.booked_hours, a.occupancy_pct, a.occupied_now]);

  section("Bookings");
  row(["Booking ID", "Created", "User", "Email", "Phone", "Location", "Slot", "Floor", "Type", "Vehicle number",
    "Start", "End", "Hours", "Amount ₹", "Status", "Payment", "Payment ref", "Paid at", "Entry time", "Exit time"]);
  for (const b of r.bookings) row([b.id, b.created_at, b.user_name, b.user_email, b.user_phone, b.location_name,
    b.slot_label, b.floor, b.type_name, b.vehicle_number, b.start_time, b.end_time, b.hours,
    b.amount, b.status, b.payment_status, b.payment_ref, b.paid_at, b.entry_time, b.exit_time]);

  section("Users");
  row(["User ID", "Name", "Email", "Phone", "Role", "Registered", "Bookings (all time)", "Bookings in range", "Paid in range ₹"]);
  for (const u of r.users) row([u.id, u.name, u.email, u.phone, u.role, u.created_at, u.bookings_all_time, u.bookings_in_range, u.paid_in_range]);

  return "\uFEFF" + lines.join("\r\n") + "\r\n"; // BOM so Excel reads UTF-8 (names, the ₹ sign)
}
