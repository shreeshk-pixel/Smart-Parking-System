// Copies sql/schema.sql, sql/migrate_v2_floors.sql, sql/seed.sql and sql/seed_demo_v3.sql into lib/setup-sql.js,
// so the SQL is bundled with the app on Vercel. Run after editing any of them: node scripts/build-setup-sql.mjs
import { readFileSync, writeFileSync } from 'fs';
const read = (f) => readFileSync(new URL('../sql/' + f, import.meta.url), 'utf8');
const out = `// GENERATED by scripts/build-setup-sql.mjs from the files in sql/. Do not edit by hand.
export const SCHEMA_SQL = ${JSON.stringify(read('schema.sql'))};
export const MIGRATE_SQL = ${JSON.stringify(read('migrate_v2_floors.sql'))};
export const SEED_SQL = ${JSON.stringify(read('seed.sql'))};
export const DEMO_SQL = ${JSON.stringify(read('seed_demo_v3.sql'))};
export const INDEX_SQL = ${JSON.stringify(read('perf_indexes.sql'))};
export const SECURITY_SQL = ${JSON.stringify(read('security_v1.sql'))};
`;
writeFileSync(new URL('../lib/setup-sql.js', import.meta.url), out);
console.log('lib/setup-sql.js written');
